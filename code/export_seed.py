#!/usr/bin/env python3
"""Export data/KRChar.csv -> d1/seed.sql (frozen snapshot for the D1 database).

The CSV is the final export from the Google Sheet; once the sheet is retired this
seed is the reproducible baseline. After that, edits live in D1 — re-export the
other way round with `export_d1_seed.py`.

Usage:
    python3 code/export_seed.py                 # write d1/seed.sql
    python3 code/export_seed.py --print-stats   # also summarise rows/weights
"""
import argparse
import csv
import os
import collections


def q(s):
    return "'" + str(s).replace("'", "''") + "'"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--print-stats", action="store_true")
    args = ap.parse_args()

    base = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    csv_path = os.path.join(base, "data", "KRChar.csv")
    out_path = os.path.join(base, "d1", "seed.sql")

    rows = []
    with open(csv_path, encoding="utf-8") as f:
        for r in csv.DictReader(f):
            ch = (r.get("Hangul") or "").strip()
            if not ch:
                continue
            rows.append({
                "cp": "%04X" % ord(ch),
                "hangul": ch,
                "category": (r.get("category") or "").strip(),
                "rr": (r.get("RR") or "").strip(),
                "keys": (r.get("Dubeolsik key") or "").strip(),
                "memo": (r.get("memo") or "").strip(),
            })

    lines = ["-- KRChar seed (generated by code/export_seed.py from data/KRChar.csv)",
             "-- Do not edit by hand; re-run the exporter instead.", ""]
    for i, r in enumerate(rows, start=1):
        lines.append(
            "INSERT OR IGNORE INTO cards (cp, hangul, category, rr, keys, memo, ord) VALUES ("
            f"{q(r['cp'])}, {q(r['hangul'])}, {q(r['category'])}, {q(r['rr'])}, "
            f"{q(r['keys'])}, {q(r['memo'])}, {i});"
        )
    lines.append("")
    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    with open(out_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))

    if args.print_stats:
        cats = collections.Counter(r["category"] for r in rows)
        print(f"rows {len(rows)} -> {out_path}")
        print("categories:", dict(sorted(cats.items(), key=lambda kv: (len(kv[0]), kv[0]))))
        print("memo filled:", sum(1 for r in rows if r["memo"]), "/", len(rows))


if __name__ == "__main__":
    main()
